def build_28_day_plan(bucket: str) -> list:
    b = bucket if bucket in PROGRAM_TEMPLATES else "mixed"
    days = []
    for wk in (1, 2, 3, 4):
        for sid in PROGRAM_TEMPLATES[b][wk]:
            if sid in SKILLS_DB:
                days.append(sid)
            else:
                # fallback если навыка нет
                fallback = list(SKILLS_DB.keys())[0]
                days.append(fallback)
    return days

