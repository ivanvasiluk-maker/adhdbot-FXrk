_PROTECTED = re.compile(r'(«[^»]*»|“[^”]*”|"[^"\n]*"|https?://[^\s<>]+|`[^`]*`|<[^>]*>)')


def preferences(user: Mapping | None) -> tuple[str, str]:
    user = user or {}
    mode = 'ty' if user.get('address_mode') == 'ty' else 'vy'
    form = user.get('address_form')
    return mode, form if form in {'male', 'female'} else 'neutral'


def address_instructions(user: Mapping | None) -> str:
    mode, form = preferences(user)
    gender = {'male': 'мужской род', 'female': 'женский род', 'neutral': 'нейтральные конструкции без указания рода'}[form]
    return f'Обращение к пользователю: только «{"ты" if mode == "ty" else "вы"}», {gender}. Не определяй пол по имени. Не меняй цитаты пользователя. Эта настройка важнее стиля тренера.'


def _case(source: str, target: str) -> str:
    return target[:1].upper() + target[1:] if source[:1].isupper() else target


def _render(part: str, mode: str, form: str) -> str:
    if mode == 'ty' and form == 'neutral':
        part = re.sub(r'\b(?:ты|вы)\s+не\s+од(?:ин|на|ни)\b', 'не обязательно справляться в одиночку', part, flags=re.I)
        part = re.sub(r'\b(?:ты|вы)\s+не\s+готов(?:а|ы)?\b', 'пока не хочется пробовать', part, flags=re.I)
    # Resolve explicit paired user forms. This is not a general inflector.
    for male, (female, plural, neutral) in PAST.items():
        paired = re.escape(male) + r'(?:\(а\)|\(-а\)|/а)'
        part = re.sub(paired, lambda m: _case(m[0], plural if mode == 'vy' else female if form == 'female' else male if form == 'male' else neutral), part, flags=re.I)
        variants = '|'.join(map(re.escape, (male, female, plural)))
        pattern = r'\b(ты|вы)(\s+(?:(?:уже|сейчас|сегодня|вчера|ещё|еще|не|пока|только|это|сам|сама)\s+){0,3})(' + variants + r')\b'
        def past(m):
            pronoun = 'вы' if mode == 'vy' else 'ты'
            verb = plural if mode == 'vy' else female if form == 'female' else male
            if mode == 'ty' and form == 'neutral':
                # Preserve negation and adverbs without manufacturing a gender.
                return _case(m[1], m[2].strip() + ' ' + neutral).strip()
            return _case(m[1], pronoun) + m[2] + verb
        part = re.sub(pattern, past, part, flags=re.I)
    for male, (female, plural, neutral) in PAST.items():
        variants = '|'.join(map(re.escape, (male, female, plural)))
        target = plural if mode == 'vy' else female if form == 'female' else male if form == 'male' else neutral
        part = re.sub(r'(Спасибо, что\s+)(' + variants + r')\b', lambda m: m[1] + target, part, flags=re.I)
        part = re.sub(r'(^|[.!?]\s+)(' + variants + r')\?', lambda m: m[1] + _case(m[2], target) + '?', part, flags=re.I)
    # Short readiness question has a known subject (the addressee).
    part = re.sub(r'\bГотов(?:а|ы)?\?', lambda m: ('Готовы?' if mode == 'vy' else 'Готова?' if form == 'female' else 'Готов?' if form == 'male' else 'Можно попробовать?'), part)
    mapping = dict(PAIRS) if mode == 'vy' else {v: k for k, v in PAIRS.items()}
    if mode == 'vy':
        mapping.pop('пришли', None)
        part = re.sub(r'(^|[.!?\n]\s*|или\s+)(пришли)\b', lambda m: m[1] + _case(m[2], 'пришлите'), part, flags=re.I)
    if mode == 'ty':
        mapping['повторите'] = 'повтори'
    part = re.sub(r'\b[А-Яа-яЁё]+\b', lambda m: _case(m[0], mapping[m[0].lower()]) if m[0].lower() in mapping else m[0], part)
    return part


def render_address(text: str, user: Mapping | None = None) -> str:
    mode, form = preferences(user)
    # Split before simplification: URLs, quotes and code stay byte-for-byte.
    chunks = _PROTECTED.split(str(text or ''))
    for i in range(0, len(chunks), 2):
        chunks[i] = plain_text(_render(chunks[i], mode, form))
    return ''.join(chunks)
