"""Conservative request routing; categories are navigation, never diagnoses."""
import re

DEVICE_LABELS = {'На телефоне': 'phone', 'На том же компьютере, где работаю': 'computer', 'И там и там': 'both'}
TASK_WORDS = ('задач', 'начать', 'начинать', 'откладыва', 'прокрастин', 'отвлека', 'отвлёк', 'отвлек', 'избега', 'работать', 'отчёт', 'отчет', 'письмо', 'черновик')
CRISIS_WORDS = ('хочу умереть', 'покончить с собой', 'убить себя', 'не хочу жить', 'суицид', 'самоубий')


def request_kind(text):
    low = (text or '').lower().replace('ё', 'е')
    if any(x in low for x in CRISIS_WORDS):
        return 'crisis'
    task = any(x.replace('ё', 'е') in low for x in TASK_WORDS)
    project = bool(re.search(r'(?:написать|готовлю|подготовить|доклад|статья|презентация).{0,45}(?:про |о |по теме ).*(?:депресси|препарат)', low))
    medication = any(x in low for x in ('антидепресс', 'венлафакс', 'феварин', 'бупропион', 'миртазап', 'сертралин', 'препарат', 'лекарств', 'психиатр'))
    physical_change = any(x in low for x in ('аппетит', 'бессонниц', 'сплю больше', 'сплю меньше', 'перестал спать', 'перестала спать'))
    depression = 'депресси' in low and not re.search(r'(?:не |нет |без )депресси', low)
    if not project and (medication or physical_change or depression):
        return 'health_or_medication'
    global_change = any(x in low for x in ('потеря активности', 'снизилась активность', 'ничего не хочется', 'ничего не хочу', 'перестал общаться', 'перестала общаться', 'не хочу общаться', 'пропало желание', 'потерял интерес', 'потеряла интерес', 'лежу между', 'лежу на диване', 'настроение упало'))
    if global_change:
        return 'emotional_state'
    if any(x in low for x in ('жена', 'муж ', 'партнер', 'отношени', 'ссор', 'конфликт', 'развод')) and (not task or any(x in low for x in ('ссор', 'конфликт', 'развод', 'начать разговор'))):
        return 'relationship'
    if task or project or any(x in low for x in ('youtube', 'ютуб', 'переписок', 'лента', 'скрол')):
        return 'task_problem'
    if any(x in low for x in ('тревожно', 'грустно', 'устал', 'нет сил', 'ленив', 'настроени')):
        return 'emotional_state'
    return 'other'


def digital_distraction(text):
    low = (text or '').lower()
    return any(x in low for x in ('youtube', 'ютуб', 'сайты перепис', 'соцсет', 'залипа', 'скрол', 'лента', 'вкладк'))


def device_from_text(text):
    low = (text or '').lower()
    phone = bool(re.search(r'(?:на|в|с)\s+(?:моем\s+)?(?:телефон|смартфон)', low))
    computer = bool(re.search(r'(?:на|за|в)\s+(?:том же\s+)?(?:компьютер|ноутбук|рабочем браузер)', low))
    return 'both' if phone and computer else 'phone' if phone else 'computer' if computer else None


def physiological_load(text):
    low = (text or '').lower()
    return any(x in low for x in ('сердце колот', 'сильное напряжение', 'дрож', 'тряс', 'тело напряж', 'нет сил', 'устал', 'не высп', 'сильная усталость'))


def observed_changes(text):
    low = (text or '').lower()
    facts = []
    if any(x in low for x in ('снизилась активность', 'потеря активности', 'лежу на диване', 'лежу между', 'ничего не хочу', 'ничего не хочется', 'пропало желание')):
        facts.append('Вы описываете снижение активности или желания что-то делать.')
    if 'аппетит' in low:
        facts.append('Вы упоминаете аппетит; важно уточнить, что именно изменилось.')
    if any(x in low for x in ('бессонниц', 'сплю больше', 'сплю меньше', 'перестал спать', 'перестала спать')):
        facts.append('Вы описываете изменения сна.')
    if any(x in low for x in ('не хочу общаться', 'перестал общаться', 'перестала общаться')):
        facts.append('Вы описываете снижение желания общаться.')
    if any(x in low for x in ('ленив', 'безволь')):
        facts.append('Слово «ленивый» — оценка себя; оно не объясняет, что изменилось.')
    return facts


def support_text(kind, facts=None):
    facts = facts or []
    lead = '\n'.join(facts) or {
        'health_or_medication': 'Вопрос касается самочувствия или лечения.',
        'emotional_state': 'Сначала разберём состояние и доступные силы.',
        'relationship': 'Сначала разберём ситуацию в отношениях.',
        'other': 'Сначала уточним сам запрос.',
        'crisis': 'Сейчас важнее безопасность и помощь живого человека.',
    }[kind]
    if kind == 'health_or_medication':
        body = ('Причина пока неизвестна. По одному описанию диагноз не определяется.\n\n'
                'Если изменения держатся, усиливаются или мешают обычной жизни, обратитесь к врачу или психиатру. '
                'Вопросы о лекарствах обсудите с назначившим их врачом; бот не подбирает препарат и дозу.\n\n'
                'Посильный шаг сейчас: запишите, когда начались изменения и как они влияют на сон, еду и обычные дела. Эту запись можно показать врачу.')
    elif kind == 'emotional_state':
        body = ('Пока неизвестно, почему это происходит. Снижение активности само по себе не доказывает лень или какой-либо диагноз.\n\n'
                'Посильный шаг: выберите одно привычное действие для заботы о себе и попробуйте его самый простой вариант. '
                'Если состояние держится, ухудшается или заметно мешает жизни, стоит обсудить его со специалистом.')
    elif kind == 'relationship':
        body = ('Пока не будем угадывать намерения другого человека.\n\n'
                'Первый шаг: отдельно запишите, что человек сказал или сделал, и что вы об этом подумали. Затем выберите одну просьбу, которую хотите обсудить.')
    elif kind == 'crisis':
        body = 'Если есть непосредственная опасность, обратитесь в местную экстренную службу. Свяжитесь с человеком, который может сейчас побыть рядом. Тренировку отложим.'
    else:
        body = 'Первый шаг: назовите одну трудность и то, что хотите изменить. После этого можно подобрать подходящее действие.'
    return lead + '\n\n' + body
